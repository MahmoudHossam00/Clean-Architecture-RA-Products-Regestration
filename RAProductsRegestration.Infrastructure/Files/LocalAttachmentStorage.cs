//using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Options;
using RAProductsRegestration.Application.Common.Interfaces.Files;
using RAProductsRegestration.Application.Common.Models;

namespace RAProductsRegestration.Infrastructure.Files;

internal sealed class LocalAttachmentStorage
    : IAttachmentStorage
{
    private readonly string _attachmentsPath;

    public LocalAttachmentStorage(
        IHostEnvironment environment,
        IOptions<AttachmentStorageOptions> options)
    {
        var configuredPath =
            options.Value.Path;

        _attachmentsPath =
            Path.IsPathRooted(configuredPath)
                ? configuredPath
                : Path.Combine(
                    environment.ContentRootPath,
                    configuredPath);

        Directory.CreateDirectory(
            _attachmentsPath);
    }

    public async Task<StoredAttachment> SaveAsync(
        FileUpload file,
        CancellationToken cancellationToken = default)
    {
        if (file.Content is null)
        {
            throw new ArgumentNullException(
                nameof(file.Content));
        }

        if (file.Length <= 0)
        {
            throw new InvalidOperationException(
                "The uploaded file is empty.");
        }

        if (string.IsNullOrWhiteSpace(
                file.FileName))
        {
            throw new InvalidOperationException(
                "File name is required.");
        }

        var attachmentId =
            Guid.NewGuid();

        var originalFileName =
            Path.GetFileName(
                file.FileName);

        var extension =
            Path.GetExtension(
                originalFileName);

        /*
         * Physical file name is generated by us.
         *
         * Example:
         * 18c9c0dd-b9cc-43a9-8f74-....pdf
         *
         * We don't trust/use the client supplied name
         * as the physical disk file name.
         */
        var storedFileName =
            $"{attachmentId:N}{extension}";

        var filePath =
            Path.Combine(
                _attachmentsPath,
                storedFileName);

        await using var destination =
            new FileStream(
                filePath,
                FileMode.CreateNew,
                FileAccess.Write,
                FileShare.None,
                AttachmentStorageConstants.BufferSize,
                useAsync: true);

        await file.Content.CopyToAsync(
            destination,
            cancellationToken);

        return new StoredAttachment(
            attachmentId,
            originalFileName,
            file.ContentType,
            file.Length);
    }

    public Task<bool> ExistsAsync(
        Guid attachmentId,
        CancellationToken cancellationToken = default)
    {
        var filePath =
            FindAttachmentPath(
                attachmentId);

        return Task.FromResult(
            filePath is not null);
    }

    public Task<Stream?> OpenReadAsync(
        Guid attachmentId,
        CancellationToken cancellationToken = default)
    {
        var filePath =
            FindAttachmentPath(
                attachmentId);

        if (filePath is null)
        {
            return Task.FromResult<Stream?>(
                null);
        }

        Stream stream =
            new FileStream(
                filePath,
                FileMode.Open,
                FileAccess.Read,
                FileShare.Read,
                AttachmentStorageConstants.BufferSize,
                useAsync: true);

        return Task.FromResult<Stream?>(
            stream);
    }

    private string? FindAttachmentPath(
        Guid attachmentId)
    {
        var searchPattern =
            $"{attachmentId:N}.*";

        return Directory
            .EnumerateFiles(
                _attachmentsPath,
                searchPattern,
                SearchOption.TopDirectoryOnly)
            .FirstOrDefault();
    }
}